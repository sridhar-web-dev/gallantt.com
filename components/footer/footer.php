(function () {

    function getStockPrice(symbol, element, name) {

        var $ = jQuery;
        var $element = $(element);

        $.ajax({

            url: '/action/get_stock_data_yahoo.php',

            type: 'GET',

            data: {
                symbol: symbol,
                _: new Date().getTime()
            },

            dataType: 'json',

            cache: false,

            timeout: 15000,

            success: function (data) {

                

                if (
                    data &&
                    data.success === true &&
                    data.price !== null &&
                    data.price !== undefined
                ) {

                    var price = parseFloat(data.price);

                    if (!isNaN(price)) {

                        $element.text(
                            price.toFixed(2)
                        );

                       
                    }

                }
            },

            error: function () {
                // Intentionally silent in production.
            }
        });
    }


    function updateFooterPrices() {

        if (typeof jQuery === 'undefined') {
            return;
        }

        // NSE
        getStockPrice(
            'GALLANTT.NS',
            '.footerNsePrice',
            'NSE'
        );

        // BSE
        getStockPrice(
            'GALLANTT.BO',
            '.footerBsePrice',
            'BSE'
        );
    }


    function updateFooterDate() {

        var now = new Date();

        var day = String(
            now.getDate()
        ).padStart(2, '0');

        var month = String(
            now.getMonth() + 1
        ).padStart(2, '0');

        var year = now.getFullYear();

        jQuery('.footerPriceDate').text(
            day + '-' + month + '-' + year
        );
    }


    /*
     * RUN IMMEDIATELY
     */
    jQuery(document).ready(function () {

        updateFooterPrices();

        updateFooterDate();

        /*
         * REFRESH PRICE EVERY 10 SECONDS
         */
        setInterval(
            updateFooterPrices,
            10000
        );

        /*
         * UPDATE DATE EVERY MINUTE
         */
        setInterval(
            updateFooterDate,
            60000
        );

    });

})();
